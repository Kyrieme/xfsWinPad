const StatementDef* FindStatement(const char* name, std::size_t len) {
    if (!name || len == 0 || len > 64) return nullptr;
    char up[65];
    for (std::size_t i = 0; i < len; ++i)
        up[i] = (char)std::toupper((unsigned char)name[i]);
    up[len] = '\0';
    for (int i = 0; i < kStatementCount; ++i) {
        const char* s = kStatements[i].name;
        std::size_t j = 0;
        for (; s[j] && j < len; ++j)
            if ((char)std::toupper((unsigned char)s[j]) != up[j]) break;
        if (s[j] == '\0' && j == len) return &kStatements[i];
    }
    return nullptr;
}

